function mulberry32(seed) {
  return function rand() {
    let t = (seed += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function round(n, d = 2) {
  const p = 10 ** d;
  return Math.round(n * p) / p;
}

function iso(d) {
  return d.toISOString().slice(0, 10);
}

function addDays(date, n) {
  const x = new Date(date);
  x.setUTCDate(x.getUTCDate() + n);
  return x;
}

function addMonths(date, n) {
  const x = new Date(date);
  x.setUTCMonth(x.getUTCMonth() + n);
  return x;
}

function parse(s) {
  const [y, m, d] = s.split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d));
}

function daysBetween(a, b) {
  return Math.round((b.getTime() - a.getTime()) / 86400000);
}

function yearsBetween(a, b) {
  return round(daysBetween(a, b) / 365.25, 2);
}

function couponDates(issueDate, redemptionDate, frequency, asOf) {
  if (frequency === "None") return [];
  const step = frequency === "Annual" ? 12 : frequency === "Semi-Annual" ? 6 : 3;
  const dates = [];
  let cursor = parse(issueDate);
  const end = parse(redemptionDate);
  // Walk from first coupon after issue
  cursor = addMonths(cursor, step);
  while (cursor <= end && dates.length < 12) {
    if (cursor > asOf) dates.push(iso(cursor));
    cursor = addMonths(cursor, step);
  }
  return dates;
}

function priceHistory(seed, lastPrice, lastYtm, calendarDays = 130) {
  const rand = mulberry32(seed);
  const points = [];
  let price = lastPrice;
  let ytm = lastYtm;
  for (let i = 0; i < calendarDays; i++) {
    const date = addDays(AS_OF, -i);
    if (date.getUTCDay() === 0 || date.getUTCDay() === 6) continue;
    points.push({
      date: iso(date),
      price: round(price, 4),
      yield: round(ytm, 4),
    });
    const shock = (rand() - 0.5) * 0.28;
    price = Math.max(70, price * (1 - shock / 100));
    ytm = Math.max(4.5, ytm + shock * 0.035);
  }
  return points.reverse();
}

function enrich(raw, seed) {
    const redemption = parse(raw.redemptionDate);
    return {
    ...raw,
    daysToMaturity: Math.max(0, daysBetween(AS_OF, redemption)),
    maturityYears: Math.max(0, yearsBetween(AS_OF, redemption)),
    couponPaymentDates: couponDates(
      raw.issueDate,
      raw.redemptionDate,
      raw.couponFrequency,
      AS_OF,
    ),
    priceHistory: priceHistory(seed, raw.lastTradedPrice, raw.ytm),
    indentureDocUrl: raw.indentureDocUrl ?? "#",
  };
}

