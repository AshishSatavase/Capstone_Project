function benchmark(seed, start, drift) {
  const rand = mulberry32(seed);
  let value = start;
  const points = [];
  for (let i = 180; i >= 0; i--) {
    const date = addDays(AS_OF, -i);
    if (date.getUTCDay() === 0 || date.getUTCDay() === 6) continue;
    value = value * (1 + drift / 252 + (rand() - 0.5) * 0.0018);
    points.push({ date: iso(date), price: round(value, 4), yield: round(6.9 + (100 - value) * 0.02, 4) });
  }
  return points;
}

